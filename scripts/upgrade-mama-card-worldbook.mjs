/* 从旧条目的 六/七 部分构建“专属阶段反馈系统”条目 */
const buildStageEntry = (name, oldEntry, extra) => {
  const sixPlus = oldEntry.content.slice(oldEntry.content.indexOf('## 六、'));
  const seven = sixPlus.includes('## 七、') ? sixPlus.slice(sixPlus.indexOf('## 七、')) : '';
  const sixOnly = sixPlus.includes('## 七、') ? sixPlus.slice(0, sixPlus.indexOf('## 七、')) : sixPlus;
  const stageBlocks = sixOnly.split(/(?=### 阶段)/).filter(b => b.startsWith('### 阶段'));
  if (stageBlocks.length !== 5) throw new Error(name + ' 阶段块数量异常: ' + stageBlocks.length);
  const rebuilt = stageBlocks.map((block, i) => {
    const out = block.replace('#### 实时思维链', '#### 固定内心OS');
    const feedback = extra.stages[i].feedback;
    const special = extra.stages[i].special;
    const osStart = out.indexOf('#### 固定内心OS');
    if (osStart === -1) throw new Error(name + ' 阶段' + (i + 1) + ' 缺少固定内心OS');
    const head = out.slice(0, osStart).trimEnd();
    const tail = out.slice(osStart).trimEnd();
    return head + '\n#### 对话反馈规则\n' + feedback + '\n' + tail + '\n#### 可触发特殊剧情\n' + special;
  }).join('\n\n---\n');
  return STAGE_INTRO[name] + '\n\n---\n' + rebuilt + (seven ? '\n\n' + seven.trim() : '');
};

/* 从旧条目的 实时思维链 构建“全阶段思维链”条目 */
const buildChainEntry = (name, oldEntry, extra) => {
  const sixPlus = oldEntry.content.slice(oldEntry.content.indexOf('## 六、'));
  const stageBlocks = sixPlus.split(/(?=### 阶段)/).filter(b => b.startsWith('### 阶段'));
  if (stageBlocks.length !== 5) throw new Error(name + ' 思维链阶段块数量异常: ' + stageBlocks.length);
  const rebuilt = stageBlocks.map((block, i) => {
    const header = block.split('\n')[0].trim();
    const chainSection = block.includes('#### 实时思维链')
      ? block.slice(block.indexOf('#### 实时思维链'))
      : '';
    const quotes = [...chainSection.matchAll(/「([^」]+)」/g)].map(m => m[0]);
    const labels = extra.chains[i].labels;
    if (quotes.length < 3) throw new Error(name + ' 阶段' + (i + 1) + ' 思维链不足: ' + quotes.length);
    const clips = quotes.map((q, j) => (j < labels.length ? labels[j] + q : '（内心独白）' + q)).join('\n');
    const chain = extra.chains[i];
    return `${header}
#### 实时分镜思维链
${clips}
#### 阶段核心考虑反馈
- 核心诉求：${chain.demand}
- 对你的行为反馈逻辑：${chain.logic}
- 绝对底线雷区：${chain.line}`;
  }).join('\n\n---\n');
  return CHAIN_INTRO[name] + '\n\n---\n' + rebuilt;
};

